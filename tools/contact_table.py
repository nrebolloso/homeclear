"""Toe-contact calibration table: hazard height (m) -> probability of a toe contact per stride that crosses it.

Shape: minimum toe clearance (MTC) in older adults is skewed, so it is modelled as lognormal with the published mean
and SD (14.1 +- 8.3 mm). Level: the raw curve says ~36% of strides would clip a 10 mm obstacle, but people lift their
feet over what they see, and the measured rate is about 1 contact in 578 strides on a 1 cm obstacle. So the table is
    p(h) = k * P(MTC < h)
with k chosen so that the rollouts, which also scale each trip's clearance by a lognormal factor
(persona.toe_clearance_cv, sim.ts), average exactly 1/578 at 10 mm. Darkness is NOT in this table: the rollouts apply
risk.dark_contact_multiplier on top, a separate and labelled assumption.

Source: Frontiers 2014 (MTC 14.1 +- 8.3 mm in older adults; ~1/578 strides contact a 1 cm obstacle), as cited in the
project plan.
  python tools/contact_table.py                  print the table
  python tools/contact_table.py --write cfg...   rewrite game.risk.contact_table.older_adult_walker in those configs
"""
import argparse, math, re, sys
from pathlib import Path

import numpy as np
import yaml

MTC_MEAN_M, MTC_SD_M = 0.0141, 0.0083
ANCHOR_H_M, ANCHOR_P = 0.010, 1 / 578
KNOTS_M = [0.0, 0.0025, 0.005, 0.0075, 0.010, 0.0125, 0.015, 0.020, 0.030, 0.050]
SOURCE = "Frontiers 2014: MTC 14.1 +- 8.3 mm (lognormal shape), ~1/578 strides contact a 1 cm obstacle (level)"


def mtc_cdf(h):
    """P(MTC < h) for a lognormal with the published mean and SD."""
    s2 = math.log(1 + (MTC_SD_M / MTC_MEAN_M) ** 2)
    mu, s = math.log(MTC_MEAN_M) - s2 / 2, math.sqrt(s2)
    h = np.asarray(h, float)
    with np.errstate(divide="ignore"):
        z = (np.log(np.maximum(h, 1e-12)) - mu) / s
    return np.where(h > 0, 0.5 * (1 + np.vectorize(math.erf)(z / math.sqrt(2))), 0.0)


def interp(knots, p, h):
    """The viewer's contactProb (sim.ts): linear between knots, clamped at both ends."""
    return np.interp(h, knots, p)


def trip_average(knots, p, h, cv):
    """What the rollouts average at height h: each trip sees h / c with c = exp(N(0, cv)) (Gauss-Hermite)."""
    x, w = np.polynomial.hermite_e.hermegauss(40)
    return float((w * interp(knots, p, h / np.exp(cv * x))).sum() / w.sum())


def table(cv):
    shape = mtc_cdf(KNOTS_M)
    k = ANCHOR_P / trip_average(KNOTS_M, shape, ANCHOR_H_M, cv)
    return [float(v) for v in (k * shape)], k


def write(cfg_path, p):
    """Replace the older_adult_walker block under contact_table, keeping the rest of the file (comments included)."""
    lines = Path(cfg_path).read_text().splitlines(keepends=True)
    i = next(n for n, l in enumerate(lines) if l.strip() == "contact_table:")
    j = next(n for n in range(i, len(lines)) if lines[n].strip() == "older_adult_walker:")
    ind = len(lines[j]) - len(lines[j].lstrip())
    end = next((n for n in range(j + 1, len(lines)) if lines[n].strip() and len(lines[n]) - len(lines[n].lstrip()) <= ind), len(lines))
    pad = " " * (ind + 2)
    block = [lines[j],
             f"{pad}# generated by tools/contact_table.py: {SOURCE}; k = p(10 mm)/P(MTC<10 mm), trip-averaged with toe_clearance_cv\n",
             f"{pad}height_m: [{', '.join(f'{h:g}' for h in KNOTS_M)}]\n",
             f"{pad}p_per_stride: [{', '.join(f'{v:.3g}' for v in p)}]\n"]
    lines[j:end] = block
    # the old comment called the table a placeholder: it is calibrated now
    text = "".join(lines)
    text = re.sub(r"\n[ \t]*# PLACEHOLDER, NOT CALIBRATED:[^\n]*\n[ \t]*# with wide spread\.[^\n]*\n", "\n", text)
    Path(cfg_path).write_text(text, newline="\n")   # LF on Windows too (.gitattributes)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", nargs="*", default=[])
    ap.add_argument("--cv", type=float, help="toe_clearance_cv (default: each config's persona value, else 0.25)")
    a = ap.parse_args()
    for cfg in a.write or [None]:
        cv = a.cv if a.cv is not None else (yaml.safe_load(Path(cfg).read_text())["game"]["persona"].get("toe_clearance_cv", 0.25) if cfg else 0.25)
        p, k = table(cv)
        print(f"{cfg or '(print)'}: cv={cv} k={k:.5f}  p(10 mm) trip-averaged = 1/{1 / trip_average(KNOTS_M, p, ANCHOR_H_M, cv):.0f}")
        print("  height_m:    ", [f"{h:g}" for h in KNOTS_M])
        print("  p_per_stride:", [f"{v:.3g}" for v in p])
        if cfg:
            write(cfg, p)
    sys.exit(0)
