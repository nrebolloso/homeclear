"""Stage 11: smoke_test_report.md (pass/fail table) + report.html for the OT (self-contained, images inlined)."""
import base64, html, json, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from common import run_stage

KEY = [("02_poses", "registered", "registered frames"), ("02_poses", "registered_pct", "registered %"),
       ("03_splat", "psnr_heldout", "PSNR held-out (dB)"), ("04_scale", "scale_error_pct", "scale error %"),
       ("05_floor", "camera_height_median_m", "median camera height (m)"),
       ("07_plan", "min_side_clearance_m", "min side clearance (m)"), ("07_plan", "path_length_m", "path length (m)"),
       ("08_hazards", "hazards", "hazards")]


def img_tag(path, alt):
    if not path.exists():
        return f"<p><i>missing: {html.escape(path.name)}</i></p>"
    return f'<img alt="{html.escape(alt)}" src="data:image/{path.suffix[1:]};base64,{base64.b64encode(path.read_bytes()).decode()}">'


def main(cfg):
    w = cfg["work"]
    res = [json.loads(p.read_text()) for p in sorted((w / "results").glob("*.json")) if p.stem != "11_report"]
    by = {r["stage"]: r for r in res}
    md = [f"# Smoke test report: {cfg['run_name']}", "", "| Stage | Status | Runtime (s) | Key metrics |", "|---|---|---|---|"]
    for r in res:
        mets = ", ".join(f"{k}={v}" for k, v in r["metrics"].items())
        md.append(f"| {r['stage']} | **{r['status']}** | {r['runtime_s']} | {mets} |")
    md += ["", "## Key numbers", ""]
    md += [f"- {label}: {by[s]['metrics'].get(k, 'n/a')}" for s, k, label in KEY if s in by]
    errs = [r for r in res if r["error"]]
    md += ["", "## Errors", ""] + ([f"### {r['stage']}\n```\n{r['error'].strip()[-3000:]}\n```" for r in errs] or ["None."])
    (w / "smoke_test_report.md").write_text("\n".join(md) + "\n")

    hz = json.loads((w / "hazards.json").read_text())["hazards"] if (w / "hazards.json").exists() else []
    rn = json.loads((w / "renders.json").read_text()) if (w / "renders.json").exists() else []
    rows = "".join(
        f"<tr><td>{h['id']}</td><td>{h['type'].replace('_', ' ')}</td><td>"
        + (f"{100 * h['min_side_clearance_m']:.0f} cm side clearance (margin {100 * h['required_margin_m']:.0f} cm)"
           if h["type"] == "tight_clearance" else f"{h['max_bump_height_cm']} cm high")
        + f"</td><td>{h['length_m']} m</td><td>({', '.join(f'{c:.2f}' for c in h['position_m'])})</td></tr>" for h in hz)
    renders = "".join(
        f"<figure><figcaption>Hazard #{r['hazard_id']}: splat render (left) and <b>VISUALIZATION ONLY</b>, "
        f"generated by {html.escape(r['backend'])} (right). Not used for any measurement.</figcaption>"
        f"<div class=pair>{img_tag(w / r['before'], 'splat render')}{img_tag(w / r['after'], 'generated visualization')}</div></figure>"
        for r in rn)
    table = "".join(f"<tr><td>{r['stage']}</td><td class={r['status']}>{r['status']}</td><td>{r['runtime_s']}</td></tr>" for r in res)
    p = by.get("07_plan", {}).get("metrics", {})
    page = f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Home Walkthrough Report</title>
<meta name="viewport" content="width=device-width, initial-scale=1"><style>
:root{{--bg:#fff;--fg:#1a1a1a;--line:#ddd}} @media (prefers-color-scheme:dark){{:root{{--bg:#151515;--fg:#eee;--line:#444}}}}
body{{background:var(--bg);color:var(--fg);font:15px/1.5 system-ui,sans-serif;max-width:1000px;margin:auto;padding:16px}}
table{{border-collapse:collapse;width:100%}} td,th{{border:1px solid var(--line);padding:4px 8px;text-align:left}}
img{{max-width:100%}} .pair{{display:grid;grid-template-columns:1fr 1fr;gap:8px}} .PASS{{color:#1a8f3a}} .FAIL{{color:#c62828}} .SKIP{{color:#999}}
</style></head><body>
<h1>Home walkthrough: {html.escape(cfg['run_name'])}</h1>
<p>All measurements come from the 3D reconstruction (Gaussian splat) of the home, scaled to metres. Images marked VISUALIZATION are generated and are not measurements.</p>
<h2>Route</h2><p>Walker width {p.get('walker_width_m', '?')} m. Path length {p.get('path_length_m', '?')} m. Narrowest point: {p.get('min_passage_width_m', '?')} m passage,
{p.get('min_side_clearance_m', '?')} m to spare on each side, at ({', '.join(str(c) for c in p.get('min_clearance_xy', []))}).</p>
{img_tag(w / 'plan_overlay.png', 'top-down map with route')}
<p><small>Map: light = floor, light green = reachable with walker, dark = obstacles, orange = floor bumps (rugs/thresholds), blue = route, green/red dots = start/goal, magenta = narrowest point.</small></p>
<h2>Hazards</h2><table><tr><th>#</th><th>Type</th><th>Measurement</th><th>Length along route</th><th>Position (x, y, z) m</th></tr>{rows}</table>
<h2>Suggested fixes (visualizations)</h2>{renders or '<p>None rendered.</p>'}
<h2>Pipeline checks</h2><table><tr><th>Stage</th><th>Status</th><th>Runtime (s)</th></tr>{table}</table>
</body></html>"""
    (w / "report.html").write_text(page)
    failed = [r["stage"] for r in res if r["status"] == "FAIL"]
    return True, {"stages_reported": len(res), "failed": failed}


if __name__ == "__main__":
    run_stage("11_report", main)
